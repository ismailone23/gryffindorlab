export function PixelIcon({ name }: { name: string }) {
  const [a, b] = icons[name];
  return (
    <span
      aria-hidden="true"
      className="grid w-fit grid-cols-[repeat(11,6px)] gap-0.5"
    >
      {a.flatMap((row, y) =>
        [...row].map((on, x) => (
          <span
            key={`${x}-${y}`}
            className="px size-1.5 rounded-[1px]"
            data-a={on === "#" || undefined}
            data-b={b[y][x] === "#" || undefined}
            // Fixed pseudo-random delay per dot, so server and client render the same.
            style={
              {
                "--d": `${((x * 7 + y * 13) % 11) * 22}ms`,
              } as React.CSSProperties
            }
          />
        )),
      )}
    </span>
  );
}
